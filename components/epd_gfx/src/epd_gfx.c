void epd_gfx_init(epd_gfx_t *g, uint8_t *buf)
{
    g->buf = buf;
}

void epd_gfx_clear(epd_gfx_t *g, bool white)
{
    memset(g->buf, white ? 0xFF : 0x00, EPD_BUF_SIZE);
}

// bit order: MSB = x%8==0
void epd_gfx_pixel(epd_gfx_t *g, int x, int y, bool white)
{
    if (x < 0 || x >= EPD_W || y < 0 || y >= EPD_H) return;
    int idx = (x >> 3) + y * (EPD_W >> 3);
    uint8_t mask = 0x80 >> (x & 7);
    if (white) g->buf[idx] |= mask;
    else       g->buf[idx] &= (uint8_t)~mask;
}

void epd_gfx_hline(epd_gfx_t *g, int x, int y, int w, bool white)
{
    for (int i = 0; i < w; i++) epd_gfx_pixel(g, x + i, y, white);
}

void epd_gfx_vline(epd_gfx_t *g, int x, int y, int h, bool white)
{
    for (int i = 0; i < h; i++) epd_gfx_pixel(g, x, y + i, white);
}

void epd_gfx_rect(epd_gfx_t *g, int x, int y, int w, int h, bool white)
{
    epd_gfx_hline(g, x, y, w, white);
    epd_gfx_hline(g, x, y + h - 1, w, white);
    epd_gfx_vline(g, x, y, h, white);
    epd_gfx_vline(g, x + w - 1, y, h, white);
}

void epd_gfx_rect_fill(epd_gfx_t *g, int x, int y, int w, int h, bool white)
{
    for (int j = 0; j < h; j++)
        epd_gfx_hline(g, x, y + j, w, white);
}

void epd_gfx_putc(epd_gfx_t *g, int x, int y, char c, bool white, int scale)
{
    if (scale < 1) scale = 1;
    if (c < 32 || c > 127) c = '?';
    const uint8_t *glyph = font5x7[(int)c - 32];

    // 5 cols, 7 rows
    for (int col = 0; col < 5; col++)
    {
        uint8_t bits = glyph[col];
        for (int row = 0; row < 7; row++)
        {
            bool on = (bits >> row) & 0x01;
            if (on)
            {
                // pixel "ink" = black => white=false
                for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++)
                        epd_gfx_pixel(g, x + col * scale + sx, y + row * scale + sy, white);
            }
        }
    }
}

void epd_gfx_print(epd_gfx_t *g, int x, int y, const char *s, bool white, int scale)
{
    int cx = x;
    while (*s)
    {
        if (*s == '\n')
        {
            cx = x;
            y += 8 * scale;
        }
        else
        {
            epd_gfx_putc(g, cx, y, *s, white, scale);
            cx += 6 * scale; // 5px + 1px space
        }
        s++;
    }
}


